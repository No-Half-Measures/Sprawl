pub fn insert(text: &str, range: Range<usize>, replacement: &str) -> String {
    text[..range.start].to_owned() + replacement + &text[range.end..]
}
pub fn previous_boundary(text: &str, offset: usize) -> usize {
    text.grapheme_indices(true)
        .rev()
        .find_map(|(i, _)| (i < offset).then_some(i))
        .unwrap_or(0)
}
pub fn next_boundary(text: &str, offset: usize) -> usize {
    text.grapheme_indices(true)
        .find_map(|(i, _)| (i > offset).then_some(i))
        .unwrap_or(text.len())
}
pub fn extend_selection(
    range: Range<usize>,
    reversed: bool,
    offset: usize,
) -> (Range<usize>, bool) {
    let anchor = if reversed { range.end } else { range.start };
    (anchor.min(offset)..anchor.max(offset), offset < anchor)
}
pub fn utf16_offset(text: &str, offset: usize) -> usize {
    let mut count = 0;
    text.chars()
        .take_while(|ch| {
            let before = count;
            count += ch.len_utf16();
            before < offset
        })
        .map(char::len_utf8)
        .sum()
}
#[cfg(test)]
mod tests {
    use super::*;
    #[::core::prelude::v1::test]
    fn grapheme_editing() {
        let s = "a\u{1f469}\u{200d}\u{1f4bb}e\u{301}z";
        let end = previous_boundary(s, s.len());
        let combining = previous_boundary(s, end);
        assert_eq!(&s[combining..end], "e\u{301}");
        let emoji = previous_boundary(s, combining);
        assert_eq!(&s[emoji..combining], "\u{1f469}\u{200d}\u{1f4bb}");
        assert_eq!(next_boundary(s, emoji), combining);
        assert_eq!(insert(s, emoji..end, "Q"), "aQz");
        assert_eq!(insert(s, emoji..combining, ""), "ae\u{301}z");
        assert_eq!(insert(s, 0..s.len(), "\u{65b0}"), "\u{65b0}");
    }

    #[::core::prelude::v1::test]
    fn selection_crosses_anchor_and_replaces() {
        assert_eq!(extend_selection(2..5, false, 1), (1..2, true));
        assert_eq!(extend_selection(1..2, true, 5), (2..5, false));
        assert_eq!(extend_selection(2..5, false, 2), (2..2, false));
        let text = "a\u{1f600}e\u{301}";
        let range = utf16_offset(text, 1)..utf16_offset(text, 3);
        assert_eq!(&text[range.clone()], "\u{1f600}");
        assert_eq!(insert(text, range, "x"), "axe\u{301}");
        assert_eq!(utf16_offset(text, 99), text.len());
        assert_eq!(previous_boundary("", 0), 0);
        assert_eq!(next_boundary("", 0), 0);
    }
}
